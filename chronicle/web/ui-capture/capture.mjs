// One-command screenshot + DOM-inspection harness for the Chronicle dashboard. See README.md.
import { resolve } from 'node:path';
import { Recorder, startRig } from './lib.mjs';
import { scenarios } from './scenes.mjs';

const outDir = process.argv[2];
if (outDir === undefined) { console.error('usage: capture.mjs <output-dir> [scenario-name-regex]'); process.exit(2); }
const filter = process.argv[3] === undefined ? null : new RegExp(process.argv[3]);
const recorder = new Recorder(resolve(outDir)), errors = [];
const rig = await startRig();
await recorder.init(rig.browser);
const started = Date.now();
try {
  for (const scenario of scenarios) {
    if (filter !== null && !filter.test(scenario.name)) continue;
    console.log(`scenario ${scenario.name}`);
    try { await scenario.run({ rig, recorder, errors }); }
    catch (cause) { errors.push(`SCENARIO FAILED ${scenario.name}: ${cause instanceof Error ? cause.stack : cause}`); console.error(`  FAILED ${scenario.name}: ${cause instanceof Error ? cause.message : cause}`); }
  }
} finally { await rig.close(); }
await recorder.writeIndex(`Generated by \`chronicle/web/ui-capture/capture.mjs\` against a scripted in-browser Chronicle server (synthetic data) in ${Math.round((Date.now() - started) / 1000)} s. Light theme and 1440x900 unless the file name says otherwise.`);
await recorder.dump('page-errors', errors);
console.log(`${recorder.entries.length} screenshots, ${errors.length} page/console errors or scenario failures`);
process.exit(errors.some(error => error.startsWith('SCENARIO FAILED')) ? 1 : 0);
