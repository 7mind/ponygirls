#!/usr/bin/env python3
"""Pinned Baboon emits forward conversions only. Mirror its typed, structural Scala
converters for this API's downgrade path. Lossy/custom types stay hand-written.
This is deliberately not a model parser: compiler output changes fail compilation.
"""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
api = root / 'generated/scala/chronicle/api'
out = root / 'server/src/main/scala/chronicle/protocol/DerivedConversions.scala'
parts = ['// Generated by scripts/protocol-conversions.py; do not edit.\n']
registrations = []
for directory, source, target, namespace in [(api/'1.1.0','1.0.0','1.1.0','chronicle.api.v1_1_0'), (api/'1.2.0','1.1.0','1.2.0','chronicle.api.v1_2_0'), (api/'1.3.0','1.2.0','1.3.0','chronicle.api.v1_3_0'), (api,'1.3.0','1.4.0','chronicle.api')]:
    old = 'chronicle.api.v'+source.replace('.','_')
    names = {p.stem.removeprefix('from-'+source+'-').split('-')[0] for p in directory.glob('from-'+source+'-*.scala')}
    forward, reverse = [], []
    for p in sorted(directory.glob('from-'+source+'-*.scala')):
        text = p.read_text()
        symbol = re.search(r'(?:object|abstract class) (Convert__\w+)',text)[1]
        custom = 'abstract class' in text
        forward.append(namespace+'.'+symbol if not custom else 'new chronicle.protocol.'+symbol+('_V11' if source=='1.0.0' else '') )
        if custom or p.stem.removeprefix("from-"+source+"-").startswith("Operation") or p.stem.removeprefix("from-"+source+"-") in {"ClientEnvelope", "LoginRequest", "LoginResponse", "IngestRequest", "IngestReceipt", "SearchQuery", "SearchFilter"}: continue
        # Only type tokens change: field accessors, string literals and IDs do not.
        text = text.replace('v1_'+source.split('.')[1]+'_0.', old+'.') if namespace=='chronicle.api' else text
        text = text.replace(old+'.','OLDTYPE.')
        text = re.sub(r'"[^"]*"|\b('+ '|'.join(sorted(names,key=len,reverse=True)) +r')\b', lambda m: m[0] if m[0].startswith('"') else old+'.'+m[0],text)
        text = text.replace('OLDTYPE.'+old+'.','')
        text = text.replace(symbol, symbol.replace('From','To'))
        text = text.replace('def versionFrom: String = "'+source+'"','def versionFrom: String = "'+target+'"').replace('def versionTo: String = "'+target+'"','def versionTo: String = "'+source+'"')
        if p.stem == 'from-'+source+'-Result':
            unsupported = 'case other => throw new IllegalArgumentException(s"Bad input: $other")'
            assert text.count(unsupported) == 1, p
            text = text.replace(unsupported, 'case _ => throw chronicle.DomainError("version-mismatch","response is not available in negotiated API version")')
        parts.append(text+'\n')
        reverse.append(namespace+'.'+symbol.replace('From','To'))
    reverse += ['new chronicle.protocol.'+name for name in (['SearchResultToV1'] if source=='1.0.0' else ['JobInfoToV11','TokensResultToV11'] if source=='1.1.0' else [])]
    registrations.append((source,target,forward,reverse))
parts.append('package chronicle.protocol {\nfinal class ProtocolConversions {\n')
for source,target,forward,reverse in registrations:
    for label,frm,to,regs in [('up',source,target,forward),('down',target,source,reverse)]:
        name=label+source.replace('.','_')
        parts.append(f'  val {name} = new baboon.runtime.shared.AbstractBaboonConversions {{ def versionsFrom = List("{frm}"); def versionTo = "{to}" }}\n')
        for reg in regs: parts.append(f'  {name}.register({reg})\n')
parts.append('}\n}\n')
out.write_text('\n'.join(parts))

# Baboon's TS emitter inlines unsupported-conversion throws instead of calling
# its stub. Route exactly the three known stubs and their three call sites to
# our external implementations. Fail closed on compiler output changes.
ts = root / 'generated/typescript/chronicle/api'
for file, function, field, depth, source in [
    ('v1_2_0/from_1_1_0_job-info.ts','job_info',None,1,'1_1_0'),
    ('v1_2_0/from_1_1_0_tokens-result.ts','tokens_result',None,1,'1_1_0'),
    ('v1_1_0/from_1_0_0_search-result.ts','search_result',None,1,'1_0_0'),
    ('v1_2_0/from_1_1_0_status-result.ts','job_info','item',1,'1_1_0'),
    ('v1_2_0/from_1_1_0_result_tokens.ts','tokens_result','from.result',1,'1_1_0'),
    ('v1_1_0/from_1_0_0_result_search.ts','search_result','from.result',1,'1_0_0'),
]:
    p=ts/file
    text=p.read_text()
    function='convert__'+function+'__from__'+source
    module='../'*(4+depth)+'protocol/typescript/conversions.js'
    if field is None:
        assert 'Custom conversion required:' in text, file
        text=f"// Custom implementation is outside the generated tree.\nexport {{ {function} }} from '{module}';\n"
    else:
        text,count=re.subn(r'\(\(\) => \{ throw new Error\("Custom conversion required: [^"]+"\); \}\)\(\)',function+'('+field+')',text)
        assert count==1,(file,count)
        text=f"import {{ {function} }} from '{module}';\n"+text
    p.write_text(text)
