import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const model = readFileSync(new URL('../../models/chronicle.baboon', import.meta.url), 'utf8');
const tokens = model.match(/"[^"]*"|[A-Za-z][A-Za-z0-9_]*|[{}:\[\]]/g);
let at = 0;
function take(expected) { const value = tokens[at++]; if (expected !== undefined && value !== expected) throw Error(`schema: expected ${expected}`); return value; }
function type() { const name = take(); if (tokens[at] !== '[') return name; take('['); const inner = type(); take(']'); return `${name}[${inner}]`; }
function data() { const fields = []; take('{'); while (tokens[at] !== '}') { const name = take(); take(':'); fields.push([name, type()]); } take('}'); return { kind: 'data', fields }; }
take('model'); take('chronicle'); take('api'); take('version'); const version = JSON.parse(take());
const definitions = {};
while (at < tokens.length) {
  let kind = take(); if (kind === 'root') kind = take(); const name = take();
  if (kind === 'data') definitions[name] = data();
  else if (kind === 'enum') { const values = []; take('{'); while (tokens[at] !== '}') values.push(take()); take('}'); definitions[name] = { kind, values }; }
  else if (kind === 'adt') { const variants = {}; take('{'); while (tokens[at] !== '}') { take('data'); variants[take()] = data(); } take('}'); definitions[name] = { kind, variants }; }
  else throw Error('unrecognized model definition');
}
const output = `// Generated by cli/scripts/schema.mjs from the sole current model; do not edit.\nexport const schemaData = ${JSON.stringify({ version, sha256: createHash('sha256').update(model).digest('hex'), definitions }, null, 2)} as const;\n`;
const path = new URL('../src/schema-data.ts', import.meta.url);
if (process.argv.includes('--check')) { if (readFileSync(path, 'utf8') !== output) throw Error('CLI boundary schema stale; run node scripts/schema.mjs'); }
else writeFileSync(path, output);
