/** The connection a [[JdbcTransactionEngine.transactionWithin]] callback gets (R-a2 M1): no server I/O starts once the
  * try's deadline passed or its watch aborted, also when the watchdog is late, through any handle the callback can reach.
  * `guard` (the try's boundary check) runs before every call that may talk to the server: statement creation and
  * execution, result-set cursor moves, savepoints, and the reads that query the server. Every handle it returns is
  * guarded the same way: statements, result sets, and `getConnection`/`getStatement` (this connection, the guarded
  * statement). Handles that would talk to the server lazily and are not needed by a try's SQL are refused with
  * [[GuardedConnection.UnsupportedCode]] rather than wrapped: `getMetaData` (database, statement, parameter and
  * result-set metadata query the catalog), `unwrap` to the driver's objects, callable statements, large objects, arrays,
  * refs and structs, and connection changes that belong to the engine (commit, rollback, autocommit, close, abort, network
  * timeout) or to the session (read-only, isolation, schema, catalog, client info, holdability, type map). Statements are
  * forward-only and read-only (an updatable or scrollable result set is refused); a statement's query timeout or
  * cancel (a cancel request is a new server connection) is refused. */
private[runtime] final class GuardedConnection(c: Connection, guard: () => Unit) extends Connection {
  import GuardedConnection.*
  export c.{nativeSQL, getAutoCommit, isClosed, isReadOnly, getCatalog, getWarnings, clearWarnings, getTypeMap, getHoldability, getNetworkTimeout,
    getClientInfo}
  private def statement[S <: Statement](resultSetType: Int, resultSetConcurrency: Int)(create: => S): S = {
    if (resultSetType != ResultSet.TYPE_FORWARD_ONLY || resultSetConcurrency != ResultSet.CONCUR_READ_ONLY) unsupported()
    guard(); create
  }
  def createStatement(): Statement = statement(ResultSet.TYPE_FORWARD_ONLY, ResultSet.CONCUR_READ_ONLY)(new GuardedStatement(c.createStatement(), this, guard))
  def createStatement(resultSetType: Int, resultSetConcurrency: Int): Statement =
    statement(resultSetType, resultSetConcurrency)(new GuardedStatement(c.createStatement(resultSetType, resultSetConcurrency), this, guard))
  def createStatement(resultSetType: Int, resultSetConcurrency: Int, resultSetHoldability: Int): Statement =
    statement(resultSetType, resultSetConcurrency)(new GuardedStatement(c.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability), this, guard))
  def prepareStatement(sql: String): PreparedStatement = prepared(c.prepareStatement(sql))
  def prepareStatement(sql: String, autoGeneratedKeys: Int): PreparedStatement = prepared(c.prepareStatement(sql, autoGeneratedKeys))
  def prepareStatement(sql: String, columnIndexes: Array[Int]): PreparedStatement = prepared(c.prepareStatement(sql, columnIndexes))
  def prepareStatement(sql: String, columnNames: Array[String]): PreparedStatement = prepared(c.prepareStatement(sql, columnNames))
  def prepareStatement(sql: String, resultSetType: Int, resultSetConcurrency: Int): PreparedStatement =
    statement(resultSetType, resultSetConcurrency)(new GuardedPreparedStatement(c.prepareStatement(sql, resultSetType, resultSetConcurrency), this, guard))
  def prepareStatement(sql: String, resultSetType: Int, resultSetConcurrency: Int, resultSetHoldability: Int): PreparedStatement =
    statement(resultSetType, resultSetConcurrency)(new GuardedPreparedStatement(c.prepareStatement(sql, resultSetType, resultSetConcurrency, resultSetHoldability), this, guard))
  private def prepared(create: => PreparedStatement): PreparedStatement =
    statement(ResultSet.TYPE_FORWARD_ONLY, ResultSet.CONCUR_READ_ONLY)(new GuardedPreparedStatement(create, this, guard))
  def setSavepoint(): Savepoint = { guard(); c.setSavepoint() }
  def setSavepoint(name: String): Savepoint = { guard(); c.setSavepoint(name) }
  def releaseSavepoint(savepoint: Savepoint): Unit = { guard(); c.releaseSavepoint(savepoint) }
  def rollback(savepoint: Savepoint): Unit = { guard(); c.rollback(savepoint) }
  def getTransactionIsolation(): Int = { guard(); c.getTransactionIsolation() }
  def getSchema(): String = { guard(); c.getSchema() }
  def isValid(timeout: Int): Boolean = { guard(); c.isValid(timeout) }
  def isWrapperFor(iface: Class[?]): Boolean = iface.isInstance(this)
  def unwrap[T](iface: Class[T]): T = if (iface.isInstance(this)) iface.cast(this) else unsupported()
  def prepareCall(sql: String): CallableStatement = unsupported()
  def prepareCall(sql: String, resultSetType: Int, resultSetConcurrency: Int): CallableStatement = unsupported()
  def prepareCall(sql: String, resultSetType: Int, resultSetConcurrency: Int, resultSetHoldability: Int): CallableStatement = unsupported()
  def getMetaData(): DatabaseMetaData = unsupported()
  def createClob(): Clob = unsupported()
  def createBlob(): Blob = unsupported()
  def createNClob(): NClob = unsupported()
  def createSQLXML(): SQLXML = unsupported()
  def createArrayOf(typeName: String, elements: Array[AnyRef]): SqlArray = unsupported()
  def createStruct(typeName: String, attributes: Array[AnyRef]): Struct = unsupported()
  def commit(): Unit = unsupported()
  def rollback(): Unit = unsupported()
  def setAutoCommit(autoCommit: Boolean): Unit = unsupported()
  def close(): Unit = unsupported()
  def abort(executor: Executor): Unit = unsupported()
  def setNetworkTimeout(executor: Executor, milliseconds: Int): Unit = unsupported()
  def setReadOnly(readOnly: Boolean): Unit = unsupported()
  def setCatalog(catalog: String): Unit = unsupported()
  def setTransactionIsolation(level: Int): Unit = unsupported()
  def setTypeMap(map: java.util.Map[String, Class[?]]): Unit = unsupported()
  def setHoldability(holdability: Int): Unit = unsupported()
  def setClientInfo(name: String, value: String): Unit = unsupported()
  def setClientInfo(properties: Properties): Unit = unsupported()
  def setSchema(schema: String): Unit = unsupported()
}
private[runtime] object GuardedConnection {
  /** A JDBC call [[GuardedConnection]] refuses inside a deadline-bound transaction (nothing is sent). */
  val UnsupportedCode = "deadline-unsupported"
  def unsupported(): Nothing = throw JdbcFailure(UnsupportedCode, None)
}

/** The statement calls of a [[GuardedConnection]]: executions guarded, results guarded, its connection the guarded one. */
private[runtime] trait GuardedExecution extends Statement {
  import GuardedConnection.unsupported
  protected def statement: Statement
  protected def owner: GuardedConnection
  protected def guard: () => Unit
  protected def guarded[A](call: => A): A = { guard(); call }
  protected def results(r: ResultSet): ResultSet = if (r == null) null else new GuardedResultSet(r, this, guard)
  final def execute(sql: String): Boolean = guarded(statement.execute(sql))
  final def execute(sql: String, autoGeneratedKeys: Int): Boolean = guarded(statement.execute(sql, autoGeneratedKeys))
  final def execute(sql: String, columnIndexes: Array[Int]): Boolean = guarded(statement.execute(sql, columnIndexes))
  final def execute(sql: String, columnNames: Array[String]): Boolean = guarded(statement.execute(sql, columnNames))
  final def executeQuery(sql: String): ResultSet = guarded(results(statement.executeQuery(sql)))
  final def executeUpdate(sql: String): Int = guarded(statement.executeUpdate(sql))
  final def executeUpdate(sql: String, autoGeneratedKeys: Int): Int = guarded(statement.executeUpdate(sql, autoGeneratedKeys))
  final def executeUpdate(sql: String, columnIndexes: Array[Int]): Int = guarded(statement.executeUpdate(sql, columnIndexes))
  final def executeUpdate(sql: String, columnNames: Array[String]): Int = guarded(statement.executeUpdate(sql, columnNames))
  final override def executeLargeUpdate(sql: String): Long = guarded(statement.executeLargeUpdate(sql))
  final override def executeLargeUpdate(sql: String, autoGeneratedKeys: Int): Long = guarded(statement.executeLargeUpdate(sql, autoGeneratedKeys))
  final override def executeLargeUpdate(sql: String, columnIndexes: Array[Int]): Long = guarded(statement.executeLargeUpdate(sql, columnIndexes))
  final override def executeLargeUpdate(sql: String, columnNames: Array[String]): Long = guarded(statement.executeLargeUpdate(sql, columnNames))
  final def executeBatch(): Array[Int] = guarded(statement.executeBatch())
  final override def executeLargeBatch(): Array[Long] = guarded(statement.executeLargeBatch())
  final override def getLargeUpdateCount(): Long = statement.getLargeUpdateCount()
  final override def setLargeMaxRows(max: Long): Unit = statement.setLargeMaxRows(max)
  final override def getLargeMaxRows(): Long = statement.getLargeMaxRows()
  final def getResultSet(): ResultSet = results(statement.getResultSet())
  final def getGeneratedKeys(): ResultSet = results(statement.getGeneratedKeys())
  final def getConnection(): Connection = owner
  final def setQueryTimeout(seconds: Int): Unit = if (seconds != 0) unsupported()
  final def cancel(): Unit = unsupported()
  final def isWrapperFor(iface: Class[?]): Boolean = iface.isInstance(this)
  final def unwrap[T](iface: Class[T]): T = if (iface.isInstance(this)) iface.cast(this) else unsupported()
}
private[runtime] final class GuardedStatement(protected val statement: Statement, protected val owner: GuardedConnection, protected val guard: () => Unit)
    extends GuardedExecution {
  export statement.{close, getMaxFieldSize, setMaxFieldSize, getMaxRows, setMaxRows, setEscapeProcessing, getQueryTimeout, getWarnings, clearWarnings,
    setCursorName, getUpdateCount, getMoreResults, setFetchDirection, getFetchDirection, setFetchSize, getFetchSize, getResultSetConcurrency,
    getResultSetType, addBatch, clearBatch, getResultSetHoldability, isClosed, setPoolable, isPoolable, closeOnCompletion, isCloseOnCompletion}
}
/** A prepared statement of a [[GuardedConnection]]: its executions guarded; `setObject`/`setNull` (which may look a type
  * up) guarded; metadata, large objects, arrays, refs and row ids refused. */
private[runtime] final class GuardedPreparedStatement(protected val statement: PreparedStatement, protected val owner: GuardedConnection,
    protected val guard: () => Unit) extends GuardedExecution with PreparedStatement {
  import GuardedConnection.unsupported
  export statement.{close, getMaxFieldSize, setMaxFieldSize, getMaxRows, setMaxRows, setEscapeProcessing, getQueryTimeout, getWarnings, clearWarnings,
    setCursorName, getUpdateCount, getMoreResults, setFetchDirection, getFetchDirection, setFetchSize, getFetchSize, getResultSetConcurrency,
    getResultSetType, addBatch, clearBatch, getResultSetHoldability, isClosed, setPoolable, isPoolable, closeOnCompletion, isCloseOnCompletion,
    setBoolean, setByte, setShort, setInt, setLong, setFloat, setDouble, setBigDecimal, setString, setBytes, setDate, setTime, setTimestamp,
    setAsciiStream, setUnicodeStream, setBinaryStream, clearParameters, setCharacterStream, setURL, setNString, setNCharacterStream, setSQLXML}
  def execute(): Boolean = guarded(statement.execute())
  def executeQuery(): ResultSet = guarded(results(statement.executeQuery()))
  def executeUpdate(): Int = guarded(statement.executeUpdate())
  override def executeLargeUpdate(): Long = guarded(statement.executeLargeUpdate())
  def setNull(parameterIndex: Int, sqlType: Int): Unit = guarded(statement.setNull(parameterIndex, sqlType))
  def setNull(parameterIndex: Int, sqlType: Int, typeName: String): Unit = guarded(statement.setNull(parameterIndex, sqlType, typeName))
  def setObject(parameterIndex: Int, x: Any): Unit = guarded(statement.setObject(parameterIndex, x))
  def setObject(parameterIndex: Int, x: Any, targetSqlType: Int): Unit = guarded(statement.setObject(parameterIndex, x, targetSqlType))
  def setObject(parameterIndex: Int, x: Any, targetSqlType: Int, scaleOrLength: Int): Unit =
    guarded(statement.setObject(parameterIndex, x, targetSqlType, scaleOrLength))
  def getMetaData(): ResultSetMetaData = unsupported()
  def getParameterMetaData(): ParameterMetaData = unsupported()
  def setRef(parameterIndex: Int, x: Ref): Unit = unsupported()
  def setBlob(parameterIndex: Int, x: Blob): Unit = unsupported()
  def setBlob(parameterIndex: Int, inputStream: InputStream, length: Long): Unit = unsupported()
  def setBlob(parameterIndex: Int, inputStream: InputStream): Unit = unsupported()
  def setClob(parameterIndex: Int, x: Clob): Unit = unsupported()
  def setClob(parameterIndex: Int, reader: Reader, length: Long): Unit = unsupported()
  def setClob(parameterIndex: Int, reader: Reader): Unit = unsupported()
  def setNClob(parameterIndex: Int, value: NClob): Unit = unsupported()
  def setNClob(parameterIndex: Int, reader: Reader, length: Long): Unit = unsupported()
  def setNClob(parameterIndex: Int, reader: Reader): Unit = unsupported()
  def setArray(parameterIndex: Int, x: SqlArray): Unit = unsupported()
  def setRowId(parameterIndex: Int, x: RowId): Unit = unsupported()
}
/** A result set of a [[GuardedConnection]]: cursor moves (which may fetch rows) and `getObject` (which may look a type up)
  * guarded; its statement the guarded one; metadata and lazily loading values (arrays, large objects, refs, structs)
  * refused. Its updates need an updatable result set, which a guarded statement never has. */
private[runtime] final class GuardedResultSet(r: ResultSet, owner: Statement, guard: () => Unit) extends ResultSet {
  import GuardedConnection.unsupported
  export r.{close, wasNull, getString, getBoolean, getByte, getShort, getInt, getLong, getFloat, getDouble, getBigDecimal, getBytes, getDate, getTime,
    getTimestamp, getAsciiStream, getUnicodeStream, getBinaryStream, getWarnings, clearWarnings, getCursorName, findColumn, getCharacterStream,
    isBeforeFirst, isAfterLast, isFirst, getRow, setFetchDirection, getFetchDirection, setFetchSize, getFetchSize, getType, getConcurrency,
    rowUpdated, rowInserted, rowDeleted, updateNull, updateBoolean, updateByte, updateShort, updateInt, updateLong, updateFloat, updateDouble,
    updateBigDecimal, updateString, updateBytes, updateDate, updateTime, updateTimestamp, updateAsciiStream, updateBinaryStream,
    updateCharacterStream, updateObject, cancelRowUpdates, moveToInsertRow, moveToCurrentRow, getURL, updateRef, updateBlob, updateClob,
    updateArray, getRowId, updateRowId, getHoldability, isClosed, updateNString, updateNClob, getNString, getNCharacterStream,
    updateNCharacterStream, getSQLXML, updateSQLXML}
  private def guarded[A](call: => A): A = { guard(); call }
  private def value[A](read: => A): A = guarded(read) match {
    case _: SqlArray | _: Blob | _: Clob | _: Ref | _: Struct => unsupported()
    case other => other
  }
  def next(): Boolean = guarded(r.next())
  def previous(): Boolean = guarded(r.previous())
  def first(): Boolean = guarded(r.first())
  def last(): Boolean = guarded(r.last())
  def beforeFirst(): Unit = guarded(r.beforeFirst())
  def afterLast(): Unit = guarded(r.afterLast())
  def absolute(row: Int): Boolean = guarded(r.absolute(row))
  def relative(rows: Int): Boolean = guarded(r.relative(rows))
  def isLast(): Boolean = guarded(r.isLast())
  def refreshRow(): Unit = guarded(r.refreshRow())
  def updateRow(): Unit = guarded(r.updateRow())
  def insertRow(): Unit = guarded(r.insertRow())
  def deleteRow(): Unit = guarded(r.deleteRow())
  def getStatement(): Statement = owner
  def getObject(columnIndex: Int): AnyRef = value(r.getObject(columnIndex))
  def getObject(columnLabel: String): AnyRef = value(r.getObject(columnLabel))
  def getObject(columnIndex: Int, map: java.util.Map[String, Class[?]]): AnyRef = value(r.getObject(columnIndex, map))
  def getObject(columnLabel: String, map: java.util.Map[String, Class[?]]): AnyRef = value(r.getObject(columnLabel, map))
  def getObject[T](columnIndex: Int, kind: Class[T]): T = value(r.getObject(columnIndex, kind))
  def getObject[T](columnLabel: String, kind: Class[T]): T = value(r.getObject(columnLabel, kind))
  def getMetaData(): ResultSetMetaData = unsupported()
  def getArray(columnIndex: Int): SqlArray = unsupported()
  def getArray(columnLabel: String): SqlArray = unsupported()
  def getBlob(columnIndex: Int): Blob = unsupported()
  def getBlob(columnLabel: String): Blob = unsupported()
  def getClob(columnIndex: Int): Clob = unsupported()
  def getClob(columnLabel: String): Clob = unsupported()
  def getNClob(columnIndex: Int): NClob = unsupported()
  def getNClob(columnLabel: String): NClob = unsupported()
  def getRef(columnIndex: Int): Ref = unsupported()
  def getRef(columnLabel: String): Ref = unsupported()
  def isWrapperFor(iface: Class[?]): Boolean = iface.isInstance(this)
  def unwrap[T](iface: Class[T]): T = if (iface.isInstance(this)) iface.cast(this) else unsupported()
}
