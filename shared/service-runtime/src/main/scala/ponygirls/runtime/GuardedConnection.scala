import java.io.{InputStream, Reader}
import java.sql.{Array as SqlArray, Blob, CallableStatement, Clob, Connection, DatabaseMetaData, NClob, ParameterMetaData, PreparedStatement,
  Ref, ResultSet, ResultSetMetaData, RowId, SQLXML, Savepoint, Statement, Struct}
