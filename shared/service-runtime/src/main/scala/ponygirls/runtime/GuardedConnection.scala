package ponygirls.runtime

import java.sql.{CallableStatement, Connection, PreparedStatement, ResultSet, Savepoint, Statement}

/** The connection a [[JdbcTransactionEngine.transactionWithin]] callback gets (R-a2 M1): `guard` (the try's boundary
  * check) runs before every statement is created or executed and before every savepoint, commit, rollback or autocommit
  * change, so no SQL starts once the try's deadline passed or its watch aborted, also when the watchdog is late. Every
  * other method is the pooled connection's. */
private[runtime] final class GuardedConnection(c: Connection, guard: () => Unit) extends Connection {
  export c.{createStatement as _, prepareStatement as _, prepareCall as _, setSavepoint as _, releaseSavepoint as _, rollback as _,
    commit as _, setAutoCommit as _, *}
  def createStatement(): Statement = { guard(); new GuardedStatement(c.createStatement(), guard) }
  def createStatement(resultSetType: Int, resultSetConcurrency: Int): Statement =
    { guard(); new GuardedStatement(c.createStatement(resultSetType, resultSetConcurrency), guard) }
  def createStatement(resultSetType: Int, resultSetConcurrency: Int, resultSetHoldability: Int): Statement =
    { guard(); new GuardedStatement(c.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability), guard) }
  def prepareStatement(sql: String): PreparedStatement = { guard(); new GuardedPreparedStatement(c.prepareStatement(sql), guard) }
  def prepareStatement(sql: String, autoGeneratedKeys: Int): PreparedStatement =
    { guard(); new GuardedPreparedStatement(c.prepareStatement(sql, autoGeneratedKeys), guard) }
  def prepareStatement(sql: String, columnIndexes: Array[Int]): PreparedStatement =
    { guard(); new GuardedPreparedStatement(c.prepareStatement(sql, columnIndexes), guard) }
  def prepareStatement(sql: String, columnNames: Array[String]): PreparedStatement =
    { guard(); new GuardedPreparedStatement(c.prepareStatement(sql, columnNames), guard) }
  def prepareStatement(sql: String, resultSetType: Int, resultSetConcurrency: Int): PreparedStatement =
    { guard(); new GuardedPreparedStatement(c.prepareStatement(sql, resultSetType, resultSetConcurrency), guard) }
  def prepareStatement(sql: String, resultSetType: Int, resultSetConcurrency: Int, resultSetHoldability: Int): PreparedStatement =
    { guard(); new GuardedPreparedStatement(c.prepareStatement(sql, resultSetType, resultSetConcurrency, resultSetHoldability), guard) }
  def prepareCall(sql: String): CallableStatement = { guard(); new GuardedCallableStatement(c.prepareCall(sql), guard) }
  def prepareCall(sql: String, resultSetType: Int, resultSetConcurrency: Int): CallableStatement =
    { guard(); new GuardedCallableStatement(c.prepareCall(sql, resultSetType, resultSetConcurrency), guard) }
  def prepareCall(sql: String, resultSetType: Int, resultSetConcurrency: Int, resultSetHoldability: Int): CallableStatement =
    { guard(); new GuardedCallableStatement(c.prepareCall(sql, resultSetType, resultSetConcurrency, resultSetHoldability), guard) }
  def setSavepoint(): Savepoint = { guard(); c.setSavepoint() }
  def setSavepoint(name: String): Savepoint = { guard(); c.setSavepoint(name) }
  def releaseSavepoint(savepoint: Savepoint): Unit = { guard(); c.releaseSavepoint(savepoint) }
  def rollback(): Unit = { guard(); c.rollback() }
  def rollback(savepoint: Savepoint): Unit = { guard(); c.rollback(savepoint) }
  def commit(): Unit = { guard(); c.commit() }
  def setAutoCommit(autoCommit: Boolean): Unit = { guard(); c.setAutoCommit(autoCommit) }
}

/** Every execution of a statement of a [[GuardedConnection]] runs its guard first. */
private[runtime] trait GuardedExecution extends Statement {
  protected def statement: Statement
  protected def guard: () => Unit
  private def guarded[A](execution: => A): A = { guard(); execution }
  final def execute(sql: String): Boolean = guarded(statement.execute(sql))
  final def execute(sql: String, autoGeneratedKeys: Int): Boolean = guarded(statement.execute(sql, autoGeneratedKeys))
  final def execute(sql: String, columnIndexes: Array[Int]): Boolean = guarded(statement.execute(sql, columnIndexes))
  final def execute(sql: String, columnNames: Array[String]): Boolean = guarded(statement.execute(sql, columnNames))
  final def executeQuery(sql: String): ResultSet = guarded(statement.executeQuery(sql))
  final def executeUpdate(sql: String): Int = guarded(statement.executeUpdate(sql))
  final def executeUpdate(sql: String, autoGeneratedKeys: Int): Int = guarded(statement.executeUpdate(sql, autoGeneratedKeys))
  final def executeUpdate(sql: String, columnIndexes: Array[Int]): Int = guarded(statement.executeUpdate(sql, columnIndexes))
  final def executeUpdate(sql: String, columnNames: Array[String]): Int = guarded(statement.executeUpdate(sql, columnNames))
  final override def executeLargeUpdate(sql: String): Long = guarded(statement.executeLargeUpdate(sql))
  final override def executeLargeUpdate(sql: String, autoGeneratedKeys: Int): Long = guarded(statement.executeLargeUpdate(sql, autoGeneratedKeys))
  final override def executeLargeUpdate(sql: String, columnIndexes: Array[Int]): Long = guarded(statement.executeLargeUpdate(sql, columnIndexes))
  final override def executeLargeUpdate(sql: String, columnNames: Array[String]): Long = guarded(statement.executeLargeUpdate(sql, columnNames))
  final def executeBatch(): Array[Int] = guarded(statement.executeBatch())
  final override def executeLargeBatch(): Array[Long] = guarded(statement.executeLargeBatch())
}
/** The prepared executions of a [[GuardedConnection]]'s prepared or callable statement. */
private[runtime] trait GuardedPreparedExecution extends GuardedExecution with PreparedStatement {
  protected def statement: PreparedStatement
  final def execute(): Boolean = { guard(); statement.execute() }
  final def executeQuery(): ResultSet = { guard(); statement.executeQuery() }
  final def executeUpdate(): Int = { guard(); statement.executeUpdate() }
  final override def executeLargeUpdate(): Long = { guard(); statement.executeLargeUpdate() }
}
private[runtime] final class GuardedStatement(protected val statement: Statement, protected val guard: () => Unit) extends GuardedExecution {
  export statement.{execute as _, executeQuery as _, executeUpdate as _, executeLargeUpdate as _, executeBatch as _, executeLargeBatch as _, *}
}
private[runtime] final class GuardedPreparedStatement(protected val statement: PreparedStatement, protected val guard: () => Unit) extends GuardedPreparedExecution {
  export statement.{execute as _, executeQuery as _, executeUpdate as _, executeLargeUpdate as _, executeBatch as _, executeLargeBatch as _, *}
}
private[runtime] final class GuardedCallableStatement(protected val statement: CallableStatement, protected val guard: () => Unit)
    extends GuardedPreparedExecution with CallableStatement {
  export statement.{execute as _, executeQuery as _, executeUpdate as _, executeLargeUpdate as _, executeBatch as _, executeLargeBatch as _, *}
}
